let language = "ru";
try {
  const saved = globalThis.localStorage?.getItem("scenario-runner-language");
  if (saved === "en" || saved === "ru") language = saved;
} catch {
  // A browser may disable local storage; the interface still works.
}
export function getLanguage() {
  return language;
}
export function setLanguage(value) {
  if (value !== "ru" && value !== "en") throw new Error("Unsupported language");
  language = value;
}
export function t(source, values = {}) {
  const template = language === "ru" ? (russian[source] ?? source) : source;
  return template.replace(
    /(\{\{.*?\}\})|\{([A-Za-z]\w*)\}/g,
    (match, literal, name) =>
      !literal && Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
export function translateDocument(root = document) {
  document.documentElement.lang = language;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  for (const attribute of ["placeholder", "aria-label", "title"]) {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => {
      node.setAttribute(
        attribute,
        t(node.getAttribute(`data-i18n-${attribute}`)),
      );
    });
  }
}
const rules = serverMessages.map(([source, english]) => {
  const names = [];
  const escaped = source.replace(/[.*+?^$()|[\]\\]/g, "\\$&");
  const pattern = escaped.replace(/\{([A-Za-z]\w*)\}/g, (_, name) => {
    names.push(name);
    return "(.*?)";
  });
  return { pattern: new RegExp(`^${pattern}$`, "s"), names, english };
});
export function serverText(message = "") {
  for (const { pattern, names, english } of rules) {
    const match = pattern.exec(message);
    if (match)
      return t(
        english,
        Object.fromEntries(
          names.map((name, index) => [name, match[index + 1]]),
        ),
      );
  }
  return message;
}
